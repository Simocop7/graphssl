def signed(x: float, digits: int = 1) -> str:
    """+1.0 / $-$1.0: a typographic minus in LaTeX tables."""
    text = f"{x:+.{digits}f}"
    return text.replace("-", "$-$", 1) if text.startswith("-") else text


def number(x: float, digits: int = 1) -> str:
    text = f"{x:.{digits}f}"
    return text.replace("-", "$-$", 1) if text.startswith("-") else text


def objectives(df: pd.DataFrame) -> list[str]:
    """The study's objectives that have rows in ``df``, in their fixed order."""
    present = set(df.method)
    return [m for m in METHODS_V2 if m in present]


def color(m: str) -> str:
    """Each objective keeps its color whichever others are present."""
    return SERIES[METHODS_V2.index(m)]


def method_name(m: str) -> str:
    return NAMES.get(m) or SUPERVISED_NAMES.get(m, m)


def reference_cells(analysis: Path) -> pd.DataFrame:
    cells = pd.read_csv(analysis / "cells.csv")
    return cells[cells.probe == REFERENCE]


def legend_below(fig: plt.Figure, handles: list, labels: list, ncol: int, y: float = 0.0) -> None:
    fig.legend(handles, labels, loc="lower center", bbox_to_anchor=(0.5, y), ncol=ncol,
               frameon=False, fontsize=7, handletextpad=0.4, columnspacing=1.2)  # fmt: skip


def dot(color: str) -> plt.Line2D:
    return plt.Line2D([], [], marker="o", ls="", color=color, ms=4.5, mec="white", mew=0.6)


