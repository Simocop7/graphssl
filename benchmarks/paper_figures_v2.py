    if e7_path.exists():
        e7 = pd.read_csv(e7_path)
        e7 = e7[(e7.condition == "graph") & (e7.probe == REFERENCE)]
        graph_untrained = e7.set_index(["dataset", "backbone"]).untrained
    rows = ["raw", "untrained", *(["untrained_graph"] if graph_untrained is not None else []),
            *methods, *SUPERVISED]  # fmt: skip
    lines = [r"\begin{tabular}{l" + "r" * 9 + "}"]
