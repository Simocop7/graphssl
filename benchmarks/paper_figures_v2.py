def write_table(out: Path, name: str, lines: list[str]) -> None:
    out.mkdir(parents=True, exist_ok=True)
    (out / name).write_text("\n".join([GENERATED, *lines]) + "\n")
    print(f"wrote {out / name}")


def tab_datasets(analysis: Path, out: Path) -> None:
    s = pd.read_csv(analysis / "datasets.csv").set_index("dataset")
    lines = [r"\begin{tabular}{lrrrrrrrr}", r"\toprule",
             r"Dataset & Nodes & Edges & Features & Classes & Homophily & Train & Val. & Test \\",
             r"\midrule"]  # fmt: skip
    for d in s.index:
        r = s.loc[d]
        cells = [f"{int(r[c]):,}".replace(",", "{,}")
                 for c in ["nodes", "edges", "features", "classes"]]  # fmt: skip
        cells.append(f"{r.edge_homophily:.2f}")
        cells += [f"{int(r[c]):,}".replace(",", "{,}") for c in ["train", "val", "test"]]
        lines.append(" & ".join([DATASET_NAMES.get(d, d), *cells]) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_table(out, "tab_datasets.tex", lines)


def tab_main(analysis: Path, out: Path) -> None:
    """Two blocks of nine columns (dataset x backbone): accuracy and, small, the gain."""
    cells = reference_cells(analysis).set_index(["dataset", "backbone", "method"])
    raw = pd.read_csv(analysis / "graph_contribution.csv")
    raw = raw[raw.probe == REFERENCE].groupby("dataset").raw_features.first()
    methods = objectives(cells.reset_index())
    rows = ["raw", "untrained", *methods, *SUPERVISED]
    lines = [r"\begin{tabular}{l" + "r" * 9 + "}", r"\toprule"]
    for block in (DATASETS[:3], DATASETS[3:]):
        lines.append(" & ".join([""] + [rf"\multicolumn{{3}}{{c}}{{{DATASET_NAMES[d]}}}"
                                        for d in block]) + r" \\")  # fmt: skip
        lines.append(" ".join(rf"\cmidrule(lr){{{2 + 3 * i}-{4 + 3 * i}}}" for i in range(3)))
        lines.append(" & ".join([""] + [BACKBONE_NAMES[b] for _ in block for b in BACKBONES])
                     + r" \\")  # fmt: skip
        lines.append(r"\midrule")
        best = {(d, b): max(cells.loc[(d, b, m), "acc"] for m in methods)
                for d in block for b in BACKBONES}  # fmt: skip
        for m in rows:
            out_cells = []
            for d in block:
                for b in BACKBONES:
                    if m == "raw":
                        if b == "gcn":
                            out_cells.append(rf"\multicolumn{{3}}{{c}}{{{raw[d]:.1f}}}")
                        continue
                    r = cells.loc[(d, b, m)]
                    acc = f"{r.acc:.1f}"
                    if m in methods and r.acc == best[(d, b)]:
                        acc = rf"\textbf{{{acc}}}"
                    gain = "" if m == "untrained" else rf"\,{{\tiny\color{{gray}}{signed(r.gain)}}}"
                    out_cells.append(acc + gain)
            name = {
                "raw": r"\textit{Raw features}",
                "untrained": r"\textit{Untrained encoder}",
            }.get(
                m, rf"\textit{{{method_name(m)}}} $\dagger$" if m in SUPERVISED else method_name(m)
            )
            lines.append(" & ".join([name, *out_cells]) + r" \\")
            if m in {"untrained", methods[-1]}:
                lines.append(r"\midrule")
        lines.append(r"\midrule" if block is DATASETS[:3] else r"\bottomrule")
    lines.append(r"\end{tabular}")
    write_table(out, "tab_main_v2.tex", lines)


