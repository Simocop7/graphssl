def tau_groups(analysis: Path) -> list[tuple[str, pd.DataFrame]]:
    """(label, rows with tau, tau_lo, tau_hi) for each factor that changes. The six datasets of
    E1 only, as in every other figure: ogbn-arxiv (3 seeds, mini-batch) is reported in its own
    section."""
    k = pd.read_csv(analysis / "kendall_tau.csv")
    k = k[k.dataset.isin(DATASETS)]
    vs_ref = k[k.comparison.str.endswith(f" vs {REFERENCE}")]
    linear = vs_ref[~vs_ref.comparison.str.startswith("knn")]
    knn = vs_ref[vs_ref.comparison.str.startswith("knn")]
    backbone = k[(k.within == REFERENCE) & k.comparison.str.contains(" vs ")
                 & ~k.comparison.str.endswith(REFERENCE)]  # fmt: skip
    e3 = pd.read_csv(analysis / "e3" / "ranking.csv")
    e4 = pd.read_csv(analysis / "trajectories" / "early_stop_tau.csv")
    reruns = pd.read_csv(analysis / "reruns_summary.csv")
    reruns = reruns[reruns.metric == "linear"].rename(columns={"kendall tau of means": "tau"})
    reruns = reruns.assign(tau_lo=np.nan, tau_hi=np.nan)
    return [
        ("Probe: other linear probes vs regularized", linear),
        ("Probe: kNN vs regularized", knn),
        ("Optimizer and learning rate: tuned vs shared", e3),
        ("Stopping: best-val. step vs 300, shared cell", e4[e4.cell == "adamw_lr5e-4"]),
        ("Stopping: best-val. step vs 300, AdamW 1e-2", e4[e4.cell == "adamw_lr1e-2"]),
        ("Machine: laptop CPU vs A2 GPU, same seeds", reruns),
        ("Backbone: each pair of backbones", backbone),
    ]


def fig_tau(analysis: Path, out: Path) -> None:
    groups = tau_groups(analysis)
    fig, ax = plt.subplots(figsize=(6.8, 2.9))
    rng = np.random.default_rng(0)
    ys = np.arange(len(groups))[::-1]
    for y, (_, rows) in zip(ys, groups, strict=True):
        tau = rows.tau.to_numpy(dtype=float)
        jitter = rng.uniform(-0.22, 0.22, size=len(tau))
        small = len(tau) <= 18
        if small:
            for lo, hi, j in zip(rows.tau_lo, rows.tau_hi, jitter, strict=True):
                if np.isfinite(lo):
                    ax.plot([lo, hi], [y + j, y + j], color=SERIES[0], lw=0.7, alpha=0.45)
        ax.plot(tau, y + jitter, "o", ms=3.4 if small else 2.6, color=SERIES[0], mec="white",
                mew=0.4, alpha=0.9 if small else 0.6)  # fmt: skip
        med = float(np.median(tau))
        ax.plot([med, med], [y - 0.34, y + 0.34], color=INK, lw=1.6)
        ax.text(1.04, y, f"median {med:.2f}  (n = {len(tau)})", va="center", fontsize=6.8,
                color=INK_2, transform=ax.get_yaxis_transform())  # fmt: skip
    ax.set_yticks(ys, [label for label, _ in groups])
    # never clip a point or an interval: the axis starts at -0.3 or below the lowest of them
    lowest = min(np.nanmin(rows[["tau", "tau_lo"]].to_numpy(dtype=float)) for _, rows in groups)
    ax.set_xlim(min(-0.3, lowest - 0.05), 1.02)
    ax.axvline(0, color=MUTED, lw=0.6)
    ax.set_xlabel("Kendall's τ between the two rankings of the objectives")
    ax.grid(axis="y", visible=False)
    fig.tight_layout()
    save(fig, out / "fig_tau")


