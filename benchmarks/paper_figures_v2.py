def fig_teaser(analysis: Path, out: Path) -> None:
    """Raw features (dashed line), untrained encoder (gray bar) and the objectives (dots,
    95% interval) per dataset (panel) and backbone (x), regularized probe."""
    cells = reference_cells(analysis)
    raw = pd.read_csv(analysis / "graph_contribution.csv")
    raw = raw[raw.probe == REFERENCE].groupby("dataset").raw_features.first()
    fig, axes = plt.subplots(2, 3, figsize=(6.8, 4.3))
    methods = objectives(cells)
    offsets = np.linspace(-0.27, 0.27, len(methods))
    for ax, d in zip(axes.flat, DATASETS, strict=True):
        g = cells[cells.dataset == d].set_index(["backbone", "method"])
        ax.axhline(raw[d], color=INK_2, lw=1.0, ls=(0, (4, 2)), zorder=1)
        for x, b in enumerate(BACKBONES):
            u = g.loc[(b, "untrained"), "acc"]
            ax.plot([x - 0.36, x + 0.36], [u, u], color=MUTED, lw=3.2, solid_capstyle="round",
                    zorder=2)  # fmt: skip
            for k, m in enumerate(methods):
                r = g.loc[(b, m)]
                xx = x + offsets[k]
                ax.plot([xx, xx], [r.acc_lo, r.acc_hi], color=color(m), lw=1.0, zorder=3)
                ax.plot(xx, r.acc, "o", ms=4, color=color(m), mec="white", mew=0.6, zorder=4)
        ax.set_xticks(range(len(BACKBONES)), [BACKBONE_NAMES[b] for b in BACKBONES])
        ax.set_xlim(-0.55, len(BACKBONES) - 0.45)
        lo, hi = ax.get_ylim()
        ax.set_ylim(lo - 0.04 * (hi - lo), hi)
        ax.grid(axis="x", visible=False)
        ax.set_title(DATASET_NAMES[d], color=INK, fontsize=8.5, fontweight="bold")
    for ax in axes[:, 0]:
        ax.set_ylabel("Test accuracy (%)")
    handles = [dot(color(m)) for m in methods]
    handles += [plt.Line2D([], [], color=MUTED, lw=3.2),
                plt.Line2D([], [], color=INK_2, lw=1.0, ls=(0, (4, 2)))]  # fmt: skip
    labels = [NAMES[m] for m in methods] + ["Untrained encoder", "Raw features"]
    legend_below(fig, handles, labels, ncol=5)
    fig.tight_layout(rect=(0, 0.09, 1, 1))
    save(fig, out / "fig_teaser")


def fig_cka(analysis: Path, out: Path) -> None:
    """Left: mean CKA between models sharing a backbone, an objective, or neither. Right: mean
    (over datasets) share of variance of each representation metric."""
    cka = pd.read_csv(analysis / "cka_grouping.csv")
    shares = pd.read_csv(analysis / "metrics_variance.csv")
    fig, (left, right) = plt.subplots(1, 2, figsize=(6.8, 2.5), width_ratios=[1, 1.25])
    pairs = [("same backbone", FACTOR_COLORS["backbone"], "Same backbone"),
             ("same method", FACTOR_COLORS["method"], "Same objective"),
             ("neither", MUTED, "Neither")]  # fmt: skip
    ys = np.arange(len(DATASETS))[::-1]
    for pair, color, _ in pairs:
        g = cka[cka.pair == pair].set_index("dataset")
        for y, d in zip(ys, DATASETS, strict=True):
            r = g.loc[d]
            left.plot([r.lo, r.hi], [y, y], color=color, lw=1.2)
            left.plot(r.cka, y, "o", ms=5, color=color, mec="white", mew=0.6)
    left.set_yticks(ys, [DATASET_NAMES[d] for d in DATASETS])
    left.set_xlim(0, 1)
    left.set_xlabel("Linear CKA between two models")
    left.grid(axis="y", visible=False)
    left.legend([dot(c) for _, c, _ in pairs], [n for _, _, n in pairs], loc="upper center",
                bbox_to_anchor=(0.5, -0.25), ncol=3, frameon=False, fontsize=7,
                handletextpad=0.3)  # fmt: skip
    metrics = [("eff_rank", "Effective rank"), ("neg_uniformity", "Uniformity"),
               ("pair_cos", "Mean pair cosine"), ("distance", "CKA distance from untrained"),
               ("smoothing_gain", "Smoothing gained")]  # fmt: skip
    components = ["backbone", "method", "method x backbone", "residual (seed)"]
    mean = shares.groupby(["metric", "component"]).share.mean()
    ys = np.arange(len(metrics))[::-1]
    for y, (metric, _) in zip(ys, metrics, strict=True):
        x0 = 0.0
        for c in components:
            w = float(mean.get((metric, c), 0.0))
            right.barh(y, w, left=x0, height=0.62, color=FACTOR_COLORS[c], edgecolor="white", lw=1)
            if w >= 0.12:
                right.text(x0 + w / 2, y, f"{100 * w:.0f}", ha="center", va="center",
                           fontsize=6.5, color="white" if c != "residual (seed)" else INK)  # fmt: skip
            x0 += w
    right.set_yticks(ys, [n for _, n in metrics])
    right.set_xlim(0, 1)
    right.set_xlabel("Share of variance, mean over datasets")
    right.grid(axis="y", visible=False)
    handles = [plt.Rectangle((0, 0), 1, 1, color=FACTOR_COLORS[c]) for c in components]
    right.legend(handles, [FACTOR_NAMES[c] for c in components], loc="upper center",
                 bbox_to_anchor=(0.5, -0.25), ncol=2, frameon=False, fontsize=7)  # fmt: skip
    fig.tight_layout()
    save(fig, out / "fig_cka")


