CHECKPOINT = re.compile(r"(?P<kind>models(?:_untrained)?)/[^/]+/(?P<backbone>\w+)/"
                        r"(?P<method>\w+?)_seed(?P<seed>\d+)\.pt$")  # fmt: skip


def arxiv_scores(probes: Path, dataset: str) -> pd.DataFrame:
    """Mean test accuracy per (backbone, method, probe) on the standard split (arxiv-year: its
    first random split), from the newest scoring of every checkpoint; raw features as backbone
    '-'. Only the regularized probe and kNN are scored on the other random splits, so they are
    left out here to keep every column on the same split."""
    records = {}
    for f in sorted((probes / dataset).glob("probes__*.json")):
        r = json.loads(f.read_text())
        for row in r["rows"]:
            ck = row.get("checkpoint")
            if ck is None:
                key = ("-", "raw", 0)
            else:
                m = CHECKPOINT.search(ck)
                if m is None:
                    continue
                method = "untrained" if m["kind"] == "models_untrained" else m["method"]
                key = (m["backbone"], method, int(m["seed"]))
            acc = {"knn": row["test_acc_knn"]}
            for p, res in row["protocols"].items():
                acc[p] = res["test_acc"]["mean"]
            records[key] = acc  # newest file wins
    df = pd.DataFrame([{"backbone": k[0], "method": k[1], "seed": k[2], **v}
                       for k, v in records.items()])  # fmt: skip
    return df.groupby(["backbone", "method"]).mean(numeric_only=True).drop(columns="seed") * 100


def tab_arxiv(probes: Path, out: Path) -> None:
    sets = [
        ("ogbn-arxiv", "Subject labels (ogbn-arxiv)"),
        ("arxiv-year", "Year labels (arxiv-year)"),
    ]
    if not all((probes / d).is_dir() for d, _ in sets):
        print("skip tab_arxiv: probe files missing")
        return
    scores = {d: arxiv_scores(probes, d) for d, _ in sets}
    cols = ["adam100", "graphssl", "knn"]
    backbones = [b for b in BACKBONES if b in scores["ogbn-arxiv"].index.get_level_values(0)]
    lines = [r"\begin{tabular}{ll" + "r" * 2 * len(cols) + "}", r"\toprule",
             " & ".join(["", ""] + [rf"\multicolumn{{{len(cols)}}}{{c}}{{{n}}}" for _, n in sets])
             + r" \\",
             r"\cmidrule(lr){3-5} \cmidrule(lr){6-8}",
             " & ".join(["Backbone", "Model"] + [PROBE_SHORT[c] for c in cols] * 2) + r" \\",
             r"\midrule"]  # fmt: skip
    raw = [f"{scores[d].loc[('-', 'raw'), c]:.1f}" for d, _ in sets for c in cols]
    lines.append(" & ".join(["--", r"\textit{Raw features}", *raw]) + r" \\")
    for b in backbones:
        lines.append(r"\midrule")
        for m in ["untrained", *[m for m in METHODS_V2 if (b, m) in scores["ogbn-arxiv"].index]]:
            vals = []
            for d, _ in sets:
                s = scores[d]
                for c in cols:
                    v = s.loc[(b, m), c] if (b, m) in s.index else np.nan
                    if m != "untrained" and np.isfinite(v):
                        u = s.loc[(b, "untrained"), c]
                        vals.append(rf"{v:.1f}\,{{\tiny\color{{gray}}{signed(v - u)}}}")
                    else:
                        vals.append("--" if not np.isfinite(v) else f"{v:.1f}")
            name = r"\textit{Untrained encoder}" if m == "untrained" else NAMES[m]
            lines.append(" & ".join([BACKBONE_NAMES[b] if m == "untrained" else "", name, *vals])
                         + r" \\")  # fmt: skip
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_table(out, "tab_arxiv.tex", lines)


